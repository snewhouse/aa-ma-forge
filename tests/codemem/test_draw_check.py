STAMP = re.compile(r"^<!-- generated by codemem draw @ [0-9a-f]{7,40} on \d{4}-\d{2}-\d{2} -->$")
REPO = Path(__file__).resolve().parents[2]


def _git(root: Path, *args: str) -> None:
    subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True)


@pytest.fixture
def repo(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A committed two-package repo with an index at the default location, cwd inside it."""
    root = tmp_path / "r"
    (root / "pkg").mkdir(parents=True)
    (root / "pkg/__init__.py").write_text("")
    (root / "pkg/a.py").write_text("from pkg import b\n\ndef run():\n    return b.helper()\n")
    (root / "pkg/b.py").write_text("def helper():\n    return 1\n")
    (root / "lib").mkdir()
    (root / "lib/__init__.py").write_text("")
    (root / "lib/c.py").write_text("from pkg import a\n\ndef go():\n    return a.run()\n")
    (root / CAPTIONS_PATH).parent.mkdir(parents=True)
    (root / CAPTIONS_PATH).write_text(json.dumps({"@start": "pkg/a.py", "pkg/": "The package."}))
    _git(root, "init", "-q")
    _git(root, "add", ".")
    _git(root, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "init")
    build_index(root, root / ".codemem/index.db", package=".")
    monkeypatch.chdir(root)
    return root


def _draw(*flags: str) -> int:
    return main(["draw", *flags])


def _files(root: Path) -> dict[Path, str]:
    return {p: p.read_text() for p in views.registered_paths(root)}


