def test_write_generates_every_registered_view_with_a_stamp(repo: Path) -> None:
    assert _draw("--write") == 0
    paths = views.registered_paths(repo)
    assert {p.name for p in paths} == {"README.md", "component.md"}  # no claude-code/ here
    for p in paths:
        assert p.is_relative_to(repo / "docs/architecture")
        assert STAMP.match(p.read_text().splitlines()[0]), p


def test_rewrite_changes_nothing_but_line_1(repo: Path) -> None:
    _draw("--write")
    before = _files(repo)
    _draw("--write")
    for p, text in _files(repo).items():
        assert text.splitlines()[1:] == before[p].splitlines()[1:]
        assert STAMP.match(text.splitlines()[0])


def test_component_view_is_l2_with_start_highlight_and_escaped_captions(repo: Path) -> None:
    (repo / CAPTIONS_PATH).write_text(json.dumps({"@start": "pkg/a.py", "pkg/": "```mermaid\n# x"}))
    _draw("--write")
    text = (repo / "docs/architecture/component.md").read_text()
    assert '["pkg/a.py"]' in text and '["lib/c.py"]' in text  # L2 = file nodes
    assert "classDef start" in text
    block = text.split(views.CAPTIONS_OPEN, 1)[1].split(views.CAPTIONS_CLOSE, 1)[0]
    assert "\\```mermaid # x" in block  # escape_prose: one inert line


def test_plugin_surface_registers_only_where_claude_code_exists(repo: Path) -> None:
    assert "plugin-surface.md" not in {p.name for p in views.registered_paths(repo)}
    assert "plugin-surface.md" in {p.name for p in views.registered_paths(REPO)}


def test_every_write_goes_through_the_generated_dir_guard(
    repo: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    rogue = views.ViewSpec(output_path=CAPTIONS_PATH, title="x", generator=views.VIEWS["readme"].generator)
    monkeypatch.setitem(views.VIEWS, "rogue", rogue)
    with pytest.raises(ValueError, match="authored sidecar"):
        views.write_views(repo, sqlite3.connect(repo / ".codemem/index.db"))
    assert json.loads((repo / CAPTIONS_PATH).read_text())["pkg/"] == "The package."


