@pytest.mark.parametrize("link", ["docs", "docs/architecture"])
def test_a_symlinked_output_dir_is_refused(repo: Path, tmp_path: Path, link: str) -> None:
    outside = tmp_path / "outside"
    (outside / "architecture").mkdir(parents=True)
    if link == "docs":
        caps = (repo / CAPTIONS_PATH).read_text()
        (repo / "docs" / CAPTIONS_PATH.split("/")[-1]).unlink()
        (repo / "docs").rmdir()
        (repo / "docs").symlink_to(outside)
        (outside / CAPTIONS_PATH.split("/")[-1]).write_text(caps)
    else:
        (repo / "docs/architecture").symlink_to(outside / "architecture")
    assert _draw("--write") == 1
    assert list((outside / "architecture").iterdir()) == []


