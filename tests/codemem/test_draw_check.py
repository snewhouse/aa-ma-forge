@pytest.mark.parametrize("gone", [".codemem", "v2"])
def test_no_graph_is_unknown_and_exit_0(repo: Path, gone: str, capsys) -> None:
    _draw("--write")
    db = repo / ".codemem/index.db"
    if gone == "v2":
        sqlite3.connect(db).execute("PRAGMA user_version = 2").connection.close()
    else:
        db.unlink()
    assert _draw("--check") == 0
    assert "UNKNOWN" in capsys.readouterr().out


